# ============================================================================
#  scripts/build.ps1 -- the single build path for this project (Gowin EDA).
#
#  Generates build\gowin\build.tcl from fpga.yaml and runs gw_sh on it from the
#  repo root (the `include and $readmemh paths are repo-relative).  Gowin
#  writes its project to impl\; the bitstream is copied to
#  build\bitstream\<name>.fs, which is what scripts\prog.ps1 loads.
#
#    scripts\build.ps1            synthesis + place & route + bitstream
#
#  gw_sh has no stage switches that keep the flow meaningful here (synthesis
#  alone takes ~1 min of a ~3 min run), so there is one entry point.  The
#  open toolchain the Tang Nano 20K build used cannot build Gowin's DDR3 IP,
#  hence Gowin.  The IP is src\ddr3_memory_interface\ (see its README).
#
#  Gates the build on timing, not on gw_sh's exit status: it fails if the
#  timing report shows negative setup slack on any clock.
# ============================================================================
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
Set-Location $root
. (Join-Path $PSScriptRoot 'toolchain.ps1')

$name = Get-FpgaName
$gwSh = 'C:\Gowin\Gowin_V1.9.12.04_x64\IDE\bin\gw_sh.exe'
if (-not (Test-Path $gwSh)) { throw "Gowin EDA not found at $gwSh" }

$yaml = Get-Content (Join-Path $root 'fpga.yaml') -Raw
$csts = @()
$inCst = $false
foreach ($line in $yaml -split "`n") {
    if ($line -match '^constraints:') { $inCst = $true; continue }
    if ($inCst -and $line -match '^[^ ]') { $inCst = $false }
    if ($inCst -and $line -match '^\s*-\s+(\S+)') { $csts += $Matches[1].Trim() }
}

foreach ($d in @('build\gowin','build\bitstream','build\logs')) {
    New-Item -ItemType Directory -Force -Path (Join-Path $root $d) | Out-Null
}

# Apple's card ROMs are copyright and are not distributed (see roms/README.md),
# so each is loaded only if the user has put it there: $readmemh is a hard
# error on a missing file, and a fresh clone must still build.  gw_sh has no
# command-line define, so without a ROM its card file is built from a copy that
# starts with that ROM's `define.  Without the Disk II's P6 ROM the //e's own
# ROM at $C600 boots a Disk II anyway (INTCXROM is on at reset); without the
# Super Serial Card's, slot 1 reads zeros and only software that drives its
# 6551 directly can use it.
$optRoms = @(
    @{ Hex = 'roms\disk2_p6.hex'; Define = 'DSK2_NO_P6_ROM'; File = 'src/disk2/disk2_card.v';
       Note = "the card's `$C600 stays zero (INTCXROM boots DOS anyway)" },
    @{ Hex = 'roms\ssc.hex';      Define = 'SSC_NO_ROM';     File = 'src/ssc.v';
       Note = "slot 1's Super Serial Card has no firmware (its 6551 still works)" }
)
$romDefine = @{}
foreach ($r in $optRoms) {
    if (-not (Test-Path -LiteralPath (Join-Path $root $r.Hex))) {
        Write-Host "== no $($r.Hex): $($r.Note)"
        $romDefine[$r.File] = $r.Define
    }
}

$tcl = @(
    "# generated by scripts/build.ps1 from fpga.yaml, overwritten on every run",
    "set_device -name GW2A-18C GW2A-LV18PG256C8/I7"
)
foreach ($src in (& (Join-Path $PSScriptRoot 'sources.ps1'))) {
    if ($romDefine.ContainsKey($src)) {
        $copy = "build/gowin/" + (Split-Path $src -Leaf)
        $body = Get-Content -Raw (Join-Path $root $src)
        [System.IO.File]::WriteAllText((Join-Path $root $copy), "``define $($romDefine[$src])`n" + $body)
        $src = $copy
    }
    $tcl += "add_file $src"
}
foreach ($c in $csts) { $tcl += "add_file $c" }
$tcl += @(
    "set_option -top_module top",
    "set_option -output_base_name top",
    "set_option -verilog_std sysv2017",
    "set_option -include_path {.}",
    "set_option -use_sspi_as_gpio 1",     # T10 key S1, M8 TF card MISO
    "set_option -use_done_as_gpio 1",     # C13 LED0
    "set_option -use_ready_as_gpio 1",    # A13 LED1
    "set_option -place_option 2",         # timing-prioritised placement (default 0: compile speed)
    "set_option -route_option 1",         # slower, better routing
    "set_option -replicate_resources 1",  # split high-fanout nets
    "run all"
)
[System.IO.File]::WriteAllText((Join-Path $root 'build\gowin\build.tcl'), ($tcl -join "`n") + "`n",
                               [System.Text.UTF8Encoding]::new($false))

# gw_sh reuses impl\ between runs; stale results have fooled this before.
# Only its results go: impl\<name>_process_config.json is the IDE project's.
foreach ($d in @('impl\gwsynthesis', 'impl\pnr', 'impl\temp')) {
    if (Test-Path $d) { Remove-Item -Recurse -Force $d }
}

# The same build as a Gowin IDE project, <name>.gprj at the repo root (the
# `include and $readmemh paths are repo-relative, so it has to live there).
# Regenerated on every run from the same file list and options, so the IDE
# and this script cannot disagree; settings changed in the IDE do not stick.
# gw_sh writes the options file for a throwaway project in build\gowin\ide.
$opts = $tcl | Where-Object { $_ -like 'set_option *' -and $_ -notlike '*output_base_name*' }
$ideTcl = @("create_project -name $name -dir build/gowin/ide -pn GW2A-LV18PG256C8/I7 -device_version C -force") + $opts
[System.IO.File]::WriteAllText((Join-Path $root 'build\gowin\ide.tcl'), ($ideTcl -join "`n") + "`n",
                               [System.Text.UTF8Encoding]::new($false))
$prevEAP = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
& $gwSh 'build/gowin/ide.tcl' *> (Join-Path $root 'build\logs\gw_sh_ide.log')
$ErrorActionPreference = $prevEAP
Set-Location $root
$cfg = "build\gowin\ide\$name\impl\${name}_process_config.json"
if (-not (Test-Path $cfg)) { throw "IDE project options not generated; see build\logs\gw_sh_ide.log" }
New-Item -ItemType Directory -Force -Path impl | Out-Null
Copy-Item $cfg "impl\${name}_process_config.json" -Force
$files = $tcl | Where-Object { $_ -like 'add_file *' } | ForEach-Object {
    $f = $_.Substring(9)
    $type = switch -regex ($f) { '\.cst$' { 'file.cst' } '\.sdc$' { 'file.sdc' } default { 'file.verilog' } }
    "        <File path=""$f"" type=""$type"" enable=""1""/>"
}
$gprj = @('<?xml version="1" encoding="UTF-8"?>', '<!DOCTYPE gowin-fpga-project>', '<Project>',
          '    <Template>FPGA</Template>', '    <Version>5</Version>',
          '    <Device name="GW2A-18C" pn="GW2A-LV18PG256C8/I7">gw2a18c-011</Device>',
          '    <FileList>') + $files + @('    </FileList>', '</Project>')
[System.IO.File]::WriteAllText((Join-Path $root "$name.gprj"), ($gprj -join "`n") + "`n",
                               [System.Text.UTF8Encoding]::new($false))

Write-Host "== gw_sh build\gowin\build.tcl"
$log = Join-Path $root 'build\logs\gw_sh.log'
$prevEAP = $ErrorActionPreference
$ErrorActionPreference = 'Continue'
try {
    & $gwSh 'build/gowin/build.tcl' 2>&1 | Tee-Object -FilePath $log | Select-String -Pattern 'ERROR|WARN \(PR|Bitstream generation|Running' | ForEach-Object { Write-Host $_.Line }
    $gwExit = $LASTEXITCODE
} finally {
    $ErrorActionPreference = $prevEAP
}

$fs = Join-Path $root 'impl\pnr\top.fs'
if ($gwExit -ne 0 -or -not (Test-Path $fs) -or (Select-String -Path $log -Pattern '^ERROR' -Quiet)) {
    throw "gw_sh failed (exit $gwExit); see build\logs\gw_sh.log and impl\pnr\top.log"
}

Copy-Item $fs (Join-Path $root "build\bitstream\$name.fs") -Force

# ── Timing gate ─────────────────────────────────────────────────────────────
$tr = Join-Path $root 'impl\pnr\top_tr_content.html'
if (-not (Test-Path $tr)) { throw "no timing report at $tr" }
$text = ((Get-Content -Raw $tr) -replace '<[^>]*>', ' ') -replace '\s+', ' '
if ($text -match 'Max Frequency Summary(.{0,1500})') { Write-Host ("Fmax:" + ($Matches[1] -replace 'Total Negative Slack.*', '')) }
if ($text -match 'Total Negative Slack Summary(.{0,600})') {
    $tnsBlock = $Matches[1]
    Write-Host "TNS: $tnsBlock"
    # any negative slack at all: mclk has ~0.1 ns to spare, so a tolerance would ship a failing DDR3 clock
    if ($tnsBlock -match '-\d+\.\d*[1-9]') {
        throw "FAILED: negative setup slack; see impl\pnr\top_tr_content.html"
    }
} else {
    throw "no 'Total Negative Slack Summary' in the timing report; cannot check timing"
}
if ($text -match 'Numbers of Hold Violated Endpoints\s+([1-9]\d*)') {
    throw "FAILED: $($Matches[1]) hold/removal timing violations; see impl\pnr\top.tr"
}
Get-Content (Join-Path $root 'impl\pnr\top.rpt.txt') | Select-String -Pattern 'Logic\s|Register\s|BSRAM\s|PLL\s|LUT' | Select-Object -First 8 | ForEach-Object { Write-Host $_.Line }
Write-Host "bitstream: build\bitstream\$name.fs"
