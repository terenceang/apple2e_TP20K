// ============================================================================
//  scripts/update-version.mjs -- update version across firmware and web companion
//
//  Reads git commit count and hash, then updates:
//    - src/version.vh           (Verilog firmware version macro)
//    - web/src/version.json     (Web companion version data)
//    - web/package.json         (npm package version)
// ============================================================================

import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..')

function getGitInfo() {
  try {
    const hash = execSync('git rev-parse --short HEAD', { cwd: ROOT }).toString().trim()
    const count = execSync('git rev-list --count HEAD', { cwd: ROOT }).toString().trim()
    const date = execSync('git log -1 --format=%cd --date=short', { cwd: ROOT }).toString().trim()
    return { hash, count, date }
  } catch (e) {
    return { hash: '0000000', count: '1', date: new Date().toISOString().slice(0, 10) }
  }
}

const { hash, count, date } = getGitInfo()
const version = `1.0.${count}`
const display = `v${version} (${hash})`
const fwStr = `\\015\\012FW:v${version} (${hash})\\015\\012`
const fwLen = Buffer.byteLength(`\r\nFW:v${version} (${hash})\r\n`, 'ascii')

// 1. src/version.vh
const vhPath = resolve(ROOT, 'src/version.vh')
const vhContent = `// Auto-generated by scripts/update-version.mjs. Do not edit manually.
\`ifndef VERSION_VH
\`define VERSION_VH

\`define FW_VER_TEXT "${fwStr}"
\`define FW_VER_LEN  8'd${fwLen}

\`endif
`
writeFileSync(vhPath, vhContent, 'utf-8')

// 2. web/src/version.json
const jsonPath = resolve(ROOT, 'web/src/version.json')
const jsonContent = JSON.stringify({ version, commit: hash, date, display }, null, 2) + '\n'
writeFileSync(jsonPath, jsonContent, 'utf-8')

// 3. web/package.json
const pkgPath = resolve(ROOT, 'web/package.json')
try {
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf-8'))
  if (pkg.version !== version) {
    pkg.version = version
    writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n', 'utf-8')
  }
} catch (e) {
  // ignore if package.json read/write fails
}

console.log(`[version] Updated to ${display} (${date})`)
