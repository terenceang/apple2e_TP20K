lines = [int(x.strip(), 16) for x in open('roms/apple2e_rom.hex')]
def byte(a): return lines[a - 0xC000]

pc = 0xFAA6
for _ in range(40):
    b0 = byte(pc)
    b1 = byte(pc+1)
    b2 = byte(pc+2)
    print(f"${pc:04X}: {b0:02X} {b1:02X} {b2:02X}")
    if b0 == 0x4C:
        target = b1 | (b2 << 8)
        print(f" -> JMP ${target:04X}")
        pc = target
        continue
    if b0 in [0x78, 0xD8, 0x18, 0x38, 0xCA, 0x88, 0xE8, 0xC8, 0xEA, 0x48, 0x68]:
        pc += 1
    elif b0 in [0xA9, 0xA2, 0xA0, 0x29, 0x09, 0x49, 0xC9, 0xE0, 0xC0, 0x90, 0xB0, 0xF0, 0xD0, 0x10, 0x30, 0x85, 0x86, 0x84, 0xA5, 0xA6, 0xA4]:
        pc += 2
    else:
        pc += 3
